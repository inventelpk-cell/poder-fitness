def translate_name(english_name: str) -> str:
    """Devuelve el nombre en español. Falla si el nombre no está en el mapa."""
    try:
        return EXACT[english_name]
    except KeyError as error:
        raise KeyError(f"Sin traducción de nombre: {english_name}") from error


def missing_names(english_names: list[str]) -> list[str]:
    return [name for name in english_names if name not in EXACT]
