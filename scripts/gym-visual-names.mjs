function dedupeWords(words) {
  const out = [];
  for (const word of words) {
    if (!word) continue;
    if (out.length > 0 && out[out.length - 1] === word) continue;
    out.push(word);
  }
  return out;
}

function cleanupSpanish(text) {
  let name = text.replace(/\s+/g, ' ').trim();
  const fixes = [
    [/\bcuadrupedia cuadrupedia\b/g, 'cuadrupedia'],
    [/\ben cuadrupedia en cuadrupedia\b/g, 'en cuadrupedia'],
    [/\blateral lateral\b/g, 'lateral'],
    [/\balterno talón toques\b/g, 'toques de talón alternos'],
    [/\btumbado curl\b/g, 'curl tumbado'],
    [/\binverso curl\b/g, 'curl inverso'],
    [/\bpalmas abajo curl\b/g, 'curl de muñeca prono'],
    [/\bpalmas curl\b/g, 'curl de muñeca supino'],
    [/\bpor encima de la cabeza curl\b/g, 'curl por encima de la cabeza'],
    [/\ba un brazo por encima de la cabeza curl\b/g, 'curl a un brazo por encima de la cabeza'],
    [/\bguillotine press de banca\b/g, 'press de banca guillotina'],
    [/\bpress de banca de\b/g, 'press de banca'],
    [/\bcon con\b/g, 'con'],
    [/\bde de\b/g, 'de'],
    [/\ben en\b/g, 'en'],
    [/\btalón toques\b/g, 'toques de talón'],
    [/\btoques alterno\b/g, 'toques alternos'],
    [/\bestiramiento cuadrupedia\b/g, 'estiramiento en cuadrupedia'],
    [/\bcuadrupedia estiramiento\b/g, 'estiramiento en cuadrupedia'],
    [/\bcon peso corporal\b/g, ''],
    [/\s{2,}/g, ' '],
  ];
  for (const [pattern, replacement] of fixes) name = name.replace(pattern, replacement);
  return name.trim();
}

function titleCase(text) {
  if (!text) return text;
  return text.charAt(0).toUpperCase() + text.slice(1);
}

function finalizeSpanishName(name) {
  let n = cleanupSpanish(name);

  const positionMoves = [
    [/^De pie (.+)$/i, '$1 de pie'],
    [/^Sentado (.+)$/i, '$1 sentado'],
    [/^Tumbado (.+)$/i, '$1 tumbado'],
    [/^De rodillas (.+)$/i, '$1 de rodillas'],
    [/^En suspensión (.+)$/i, '$1 en suspensión'],
  ];
  for (const [pattern, suffix] of positionMoves) {
    const match = n.match(pattern);
    if (!match) continue;
    const rest = match[1].trim();
    const tail = suffix.replace('$1', '').trim();
    if (rest.toLowerCase().endsWith(tail)) continue;
    n = cleanupSpanish(`${rest} ${tail}`);
  }

  if (/^Alterno /i.test(n)) {
    n = cleanupSpanish(`${n.replace(/^Alterno /i, '')} alterno`);
  }

  const gripLead = n.match(
    /^(?:(Cerrado|Ancho|Neutro|Supino)(?:\s+agarre)?|Agarre\s+(cerrado|ancho|neutro|supino))\s+(.+)$/i,
  );
  if (gripLead) {
    const grip = (gripLead[1] || gripLead[2]).toLowerCase();
    n = cleanupSpanish(`${gripLead[3]}, agarre ${grip}`);
  }

  n = n
    .replace(/^Ancho (press de banca\b.+)$/i, '$1, agarre ancho')
    .replace(/^Cerrado (press de banca\b.+)$/i, '$1, agarre cerrado')
    .replace(
      /^(Inclinado|Declinado) press de banca agarre (cerrado|ancho|supino|neutro) con (.+)$/i,
      (_, pos, grip, gear) => `Press de banca ${pos.toLowerCase()} con ${gear}, agarre ${grip}`,
    )
    .replace(
      /^Agarre (supino|neutro|cerrado|ancho) (.+ con (?:barra|mancuernas|polea|banda|máquina|fitball).*)$/i,
      (_, grip, rest) => `${rest}, agarre ${grip}`,
    )
    .replace(/^Tobillo círculos$/i, 'Círculos de tobillo')
    .replace(/^Arquero (dominadas|flexiones)$/i, (_, ex) => `${ex} de arquero`)
    .replace(/^Elbow fondos$/i, 'Fondos en codos')
    .replace(/^Pike cobra flexiones$/i, 'Flexiones pike a cobra')
    .replace(/^Pike flexiones$/i, 'Flexiones pike')
    .replace(/^De pie remo$/i, 'Remo de pie')
    .replace(/^Suspended (.+)$/i, (_, rest) => `${rest} en suspensión`)
    .replace(/^Con giro (.+)$/i, (_, rest) => `${rest} con giro`)
    .replace(/^Inverso cerrado agarre (.+)$/i, (_, rest) => `${rest}, agarre cerrado inverso`)
    .replace(/^De pie deltoides posterior remo\b/i, 'Remo de deltoides posterior de pie')
    .replace(/\belbow\b/gi, 'codos')
    .replace(/\boverhead\b/gi, 'por encima de la cabeza')
    .replace(/^Un brazo (.+)$/i, (_, rest) => `${rest} a una mano`)
    .replace(/^Two brazo (.+)$/i, (_, rest) => `${rest} a dos manos`)
    .replace(/^A un brazo (.+)$/i, (_, rest) => `${rest} a una mano`)
    .replace(/^Rear elevación lateral(.*)$/i, 'Elevación lateral posterior$1')
    .replace(/^Palmada flexiones$/i, 'Flexiones con palmada')
    .replace(/^Jackknife abdominal$/i, 'Abdominal en navaja')
    .replace(/^London puente$/i, 'Puente de Londres')
    .replace(/^Pliométric[oa] sentadilla(.*)$/i, (_, tail) => `Sentadilla pliométrica${tail}`)
    .replace(/^Completo sentadilla(.*)$/i, (_, tail) => `Sentadilla completa${tail}`)
    .replace(/^Giro remo(.*)$/i, (_, tail) => `Remo con giro${tail}`)
    .replace(/^Sentadilla ting remo$/i, 'Remo en sentadilla')
    .replace(/^Two brazo (.+)$/i, (_, rest) => `${rest} a dos brazos`)
    .replace(/^Twin asa (.+)$/i, (_, rest) => `${rest} con asas dobles`)
    .replace(/^Auto inverso (.+)$/i, (_, rest) => `${rest} inverso asistido`)
    .replace(/^Lastrado muscle$/i, 'Muscle-up lastrado')
    .replace(/\bSitted\b/gi, 'sentado')
    .replace(/\bRear\b/gi, 'posterior')
    .replace(/\bTwo\b/gi, 'dos')
    .replace(/\bTwin\b/gi, 'doble')
    .replace(/\bGlutes\b/gi, 'glúteos')
    .replace(/\bMuscle\b/gi, 'muscle-up')
    .replace(/\bAuto\b/gi, '')
    .replace(/\bInverse\b/gi, 'inverso')
    .replace(/\bting\b/gi, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

  return cleanupSpanish(titleCase(n));
}

